def build_pharmacophore_pml(features, output_path):
    """Generate a PyMOL pharmacophore visualization."""
    lines = [
        "# α9α10 Allosteric Pharmacophore",
        "# Derived from SAR + IFP + pocket geometry",
        "# Generated by lean_pipeline/phase15_pharmacophore/build_pharmacophore.py",
        "",
        "# Load receptor",
        "load ../../02_receptor/a9a10_2to3_apo.pdb, receptor",
        "",
        "# Colour scheme",
        "util.cbow 'alpha9', 'blue'",
        "util.cbow 'alpha10', 'orange'",
        "set_color hbd, [0.0, 0.0, 1.0]",
        "set_color hba, [1.0, 0.0, 0.0]",
        "set_color hyd, [0.0, 0.7, 0.0]",
        "set_color neg, [1.0, 1.0, 0.0]",
        "set_color pol, [0.0, 1.0, 1.0]",
        "set_color forb, [0.5, 0.0, 0.5]",
        "",
        "# Style",
        "hide everything",
        "show cartoon, receptor",
        "color gray80, receptor",
        "set transparency, 0.3, receptor",
        "",
    ]
    
    for feat in features:
        if feat["type"] == "H-bond donor":
            color = "hbd"
            label = "HBD"
        elif feat["type"] == "H-bond acceptor":
            color = "hba"
            label = "HBA"
        elif feat["type"] == "hydrophobic":
            color = "hyd"
            label = "HYD"
        elif feat["type"] == "negative charge":
            color = "neg"
            label = "NEG"
        elif feat["type"] == "polar":
            color = "pol"
            label = "POL"
        else:
            color = "gray"
            label = feat["type"][:3].upper()
        
        lines.append(f"# {feat['name']}: {feat['description']}")
        for res in feat["residues"]:
            subunit, resnum = res.split(":")
            sel = f"resn {label} and name CA"
            lines.append(f"sele {feat['name']}_{res.replace(':', '_')}, "
                          f"resi {resnum} and chain {'A' if 'alpha9' in subunit else 'D'}")
            lines.append(f"show spheres, {feat['name']}_{res.replace(':', '_')}")
            lines.append(f"color {color}, {feat['name']}_{res.replace(':', '_')}")
            lines.append(f"set sphere_scale, 0.5, {feat['name']}_{res.replace(':', '_')}")
            lines.append(f"label {feat['name']}_{res.replace(':', '_')} and name CA, "
                          f"'{label} {res}'")
            lines.append(f"set label_size, 14, {feat['name']}_{res.replace(':', '_')}")
            lines.append("")
    
    # Forbidden regions
    lines.append("# Forbidden regions (steric clashes)")
    for forb in FORBIDDEN_REGIONS:
        for res in forb["residues"]:
            subunit, resnum = res.split(":")
            sel = f"forbidden_{res.replace(':', '_')}"
            lines.append(f"sele {sel}, resi {resnum} and chain {'A' if 'alpha9' in subunit else 'D'}")
            lines.append(f"show spheres, {sel}")
            lines.append(f"color forb, {sel}")
            lines.append(f"set sphere_scale, 0.3, {sel}")
            lines.append("")
    
    # Distances
    lines.append("# Pharmacophore distances")
    for i, f1 in enumerate(features):
        for f2 in features[i+1:]:
            if f1["residues"] and f2["residues"]:
                r1 = f1["residues"][0]
                r2 = f2["residues"][0]
                sub1, num1 = r1.split(":")
                sub2, num2 = r2.split(":")
                chain1 = "A" if "alpha9" in sub1 else "D"
                chain2 = "A" if "alpha9" in sub2 else "D"
                lines.append(f"distance {f1['name']}_{f2['name']}, "
                              f"resi {num1} and chain {chain1} and name CA, "
                              f"resi {num2} and chain {chain2} and name CA, "
                              f"{f1['distance_A']}")
    lines.append("")
    
    # View
    lines.extend([
        "# View",
        "bg_color white",
        "set ray_opaque_background, 0",
        "center receptor",
        "zoom receptor",
        "set_view (\\",
        "     1.0000000,    0.0000000,    0.0000000,\\",
        "     0.0000000,    1.0000000,    0.0000000,\\",
        "     0.0000000,    0.0000000,    1.0000000,\\",
        "     0.0000000,    0.0000000, -200.0000000,\\",
        "   -50.0000000,   50.0000000,  200.0000000,\\",
        "   -10.0000000,  410.0000000,  -10.0000000 )",
        "",
        "# Legend",
        "cmd.extend('legend', lambda: None)",
        "",
    ])
    
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")

def write_pharmacophore_csv(features, output_path):
    """Write pharmacophore features as CSV."""
    with open(output_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=features[0].keys())
        writer.writeheader()
        writer.writerows(features)

def write_summary(features, output_path):
    lines = [
        "α9α10 ALLOSTERIC PHARMACOPHORE",
        "=" * 60,
        "",
        "Derived from: SAR analysis + interaction fingerprints + pocket geometry",
        "",
        "FEATURES:",
        "",
    ]
    
    for feat in features:
        ess = "ESSENTIAL" if feat["essential"] else "optional"
        stereo = "stereo-sensitive" if feat["stereochem_sensitive"] else "stereo-insensitive"
        lines.append(f"  {feat['name']:8s}  {feat['type']:20s}  {ess:9s}  {stereo}")
        lines.append(f"           {feat['description']}")
        lines.append(f"           Residues: {', '.join(feat['residues'])}")
        lines.append(f"           Max distance: {feat['distance_A']} Å")
        lines.append("")
    
    lines.extend([
        "FORBIDDEN REGIONS:",
        "",
    ])
    for forb in FORBIDDEN_REGIONS:
        lines.append(f"  {forb['name']:12s}  {forb['description']}")
        lines.append(f"               Residues: {', '.join(forb['residues'])}")
        lines.append(f"               Max volume: {forb['max_volume_A3']} ų")
        lines.append("")
    
    lines.extend([
        "DESIGN RULES:",
        "",
        "1. Must contain H-bond donor near W176/S175 (HBD1)",
        "2. Must contain H-bond acceptor near Y120/W81 (HBA1)",
        "3. Must contain negative charge near R143/D145 (NEG1)",
        "4. Hydrophobic region near Y224/Y217 improves affinity (HYD1)",
        "5. Polar group near N57/V55 improves selectivity (POL1)",
        "6. Must avoid steric clash with M2 helix (FORBIDDEN1)",
        "7. L-stereochemistry preferred (D-ascorbate shows 3x weaker binding)",
        "",
        "SELECTIVITY DETERMINANTS:",
        "",
        "  α9α10-specific residues in pharmacophore:",
        "    W176 (α9 ECD) — not present in α7 or α4β2",
        "    Y224 (α9 ECD) — unique aromatic position",
        "    R143 (α10 ECD) — charge complementarity",
        "    D145 (α10 ECD) — stereospecific H-bond",
    ])
    
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")

def main():
    print("Building pharmacophore...")
    
    print("Writing PML...")
    build_pharmacophore_pml(PHARMACOPHORE_FEATURES, OUT / "pharmacophore.pml")
    
    print("Writing CSV...")
    write_pharmacophore_csv(PHARMACOPHORE_FEATURES, OUT / "pharmacophore_features.csv")
    
    print("Writing summary...")
    write_summary(PHARMACOPHORE_FEATURES, OUT / "pharmacophore_summary.txt")
    
    print("Done.")

if __name__ == "__main__":
    main()
